x = int(input("Введите координату X: "))
y = int(input("Введите координату Y: "))

if x == 0 and y == 0:
    print(0)  # Точка в начале координат
elif x == 0 or y == 0:
    # Если одна координата 0, но не обе — точка на оси
    if y == 0:
        print(1)  # Лежит на оси OX (игрек равен нулю)
    else:
        print(2)  # Лежит на оси OY (икс равен нулю)
else:
    print(3)  # Не лежит на осях